package clickItem

import (
	"image"

	"math/rand"
)

// T题_静态扰动 经典静态题型：提示栏展示目标图标，
// 网格中混入干扰图标，全部图标经过随机渲染管线。
// 任务：识别提示图标并在网格中按序点击。
type T题_静态扰动 struct{}

// Q题型_名称 返回题型名称，用于日志与统计。
func (T题_静态扰动) Q题型_名称() string { return "静态扰动" }

// T题_生成 生成一张静态PNG挑战图。
func (j T题_静态扰动) T题_生成(难度 int, 随机 *rand.Rand) (*T题_挑战, error) {
	if _, 局_错误 := 素材_取(); 局_错误 != nil {
		return nil, 局_错误
	}
	局_布局, 局_错误 := 布局_生成(难度)
	if 局_错误 != nil {
		return nil, 局_错误
	}
	局_画布 := 渲染_新建画布()
	渲染_画提示栏(局_画布, 局_布局.目标id, 随机)
	渲染_画网格(局_画布, 局_布局, 随机, 0)
	渲染_加装饰(局_画布, 随机)
	return &T题_挑战{
		Z帧:   []*image.RGBA{局_画布},
		M目标: 局_布局.目标,
		G格式: "png",
	}, nil
}

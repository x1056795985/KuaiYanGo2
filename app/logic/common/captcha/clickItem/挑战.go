// Package clickItem 提供点击式验证码的各类题型成员。
// 每个成员负责生成一种"画布帧 + 有序目标矩形"的挑战，
// 交互协议(显示固定尺寸图片+回传点击坐标)与外部签名完全不变。
package clickItem

import (
	"crypto/rand"
	"errors"
	"image"
)

const (
	// 格_列数 网格列数。
	格_列数 = 7
	// 格_行数 网格行数(不含提示栏)。
	格_行数 = 3
	// 格_边长 单个图标格子的边长(像素)。
	格_边长 = 48
	// T题_点击数 需要按序点击的目标数量。
	T题_点击数 = 4
	// T题_最大难度 干扰图标数量上限。
	T题_最大难度 = 格_列数*格_行数 - T题_点击数 - 1
	// B布_画布宽 整张验证码图片宽度(7格)。
	B布_画布宽 = 格_列数 * 格_边长
	// B布_画布高 整张验证码图片高度(提示栏+3行)。
	B布_画布高 = (格_行数 + 1) * 格_边长
	// 布_提示栏宽 左侧"请依次点击"文字图占用的宽度。
	布_提示栏宽 = 150
)

// T题_挑战 所有题型成员的统一产物：
// 单帧为静态题(编码为PNG/JPEG)，多帧为动态题(编码为GIF)；
// M目标即为存入验证码存储的有序矩形切片，验证端零改动。
type T题_挑战 struct {
	Z帧   []*image.RGBA     // 画布帧序列，长度1为静态题
	Y延迟 []int             // 每帧延迟(单位1/100秒)，静态题为nil
	M目标 []image.Rectangle // 按点击顺序排列的目标格子
	G格式 string            // 静态题编码格式:"png"或"jpeg"，多帧固定gif
}

// 布局_结果 一次挑战的图标摆放方案。
type 布局_结果 struct {
	网格   []int             // 每格的图标id，0表示空白格
	目标   []image.Rectangle // 与点击顺序对应的目标格子
	目标id []int             // 与点击顺序对应的目标图标id
}

// 布局_生成 按难度随机抽取图标并摆放网格：
// 图标选取与位置使用加密随机数，保证不可预测；
// 干扰图标与目标图标混洗后居中填入网格。
func 布局_生成(难度 int) (布局_结果, error) {
	var 局_布局 布局_结果
	if 难度 < 0 {
		难度 = 0
	} else if 难度 > T题_最大难度 {
		难度 = T题_最大难度
	}
	局_图标 := make([]int, 90)
	for 局_i := range 局_图标 {
		局_图标[局_i] = 局_i + 1
	}
	if 局_错误 := 随机_洗牌(局_图标); 局_错误 != nil {
		return 局_布局, 局_错误
	}
	局_图标 = 局_图标[:T题_点击数+难度]
	局_目标id := append([]int(nil), 局_图标[:T题_点击数]...)
	if 局_错误 := 随机_洗牌(局_图标); 局_错误 != nil {
		return 局_布局, 局_错误
	}

	局_网格 := make([]int, 格_列数*格_行数)
	局_左边距 := (len(局_网格) - len(局_图标)) / 2
	copy(局_网格[局_左边距:], 局_图标)

	局_目标 := make([]image.Rectangle, T题_点击数)
	for 局_序, 局_id := range 局_网格 {
		if 局_id == 0 {
			continue
		}
		局_x := 局_序 % 格_列数 * 格_边长
		局_y := 局_序/格_列数*格_边长 + 格_边长
		for 局_目标序, 局_目标图标 := range 局_目标id {
			if 局_目标图标 == 局_id {
				局_目标[局_目标序] = image.Rect(局_x, 局_y, 局_x+格_边长, 局_y+格_边长)
			}
		}
	}
	return 布局_结果{网格: 局_网格, 目标: 局_目标, 目标id: 局_目标id}, nil
}

// 随机_取整数 使用加密随机数返回 [0,上限) 内的整数。
func 随机_取整数(上限 int) (int, error) {
	if 上限 <= 0 || 上限 > 256 {
		return 0, errors.New("随机范围必须在1到256之间")
	}
	局_排除 := 256 - 256%上限
	var 局_字节 [1]byte
	for {
		if _, 局_错误 := rand.Read(局_字节[:]); 局_错误 != nil {
			return 0, 局_错误
		}
		if int(局_字节[0]) < 局_排除 {
			return int(局_字节[0]) % 上限, nil
		}
	}
}

// 随机_洗牌 使用加密随机数进行Fisher-Yates洗牌。
func 随机_洗牌[值类型 any](值 []值类型) error {
	for 局_i := len(值) - 1; 局_i > 0; 局_i-- {
		局_j, 局_错误 := 随机_取整数(局_i + 1)
		if 局_错误 != nil {
			return 局_错误
		}
		值[局_i], 值[局_j] = 值[局_j], 值[局_i]
	}
	return nil
}

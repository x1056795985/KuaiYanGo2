package clickItem

import (
	"image"

	"math/rand"
)

// T题_遮挡脑补 静态"缺失脑补"题型：网格中的图标有较大概率
// 被另一图标的缩放剪影盖住一角，选择性破坏判别性特征。
// 人类依靠格式塔补全能力轻松识别残缺图标，
// 模板匹配与分类器因关键区域缺失而置信度下降。
type T题_遮挡脑补 struct{}

// Q题型_名称 返回题型名称，用于日志与统计。
func (T题_遮挡脑补) Q题型_名称() string { return "遮挡脑补" }

// T题_生成 生成一张带随机遮挡的静态挑战图。
func (j T题_遮挡脑补) T题_生成(难度 int, 随机 *rand.Rand) (*T题_挑战, error) {
	if _, 局_错误 := 素材_取(); 局_错误 != nil {
		return nil, 局_错误
	}
	局_布局, 局_错误 := 布局_生成(难度)
	if 局_错误 != nil {
		return nil, 局_错误
	}
	局_画布 := 渲染_新建画布()
	渲染_画提示栏(局_画布, 局_布局.目标id, 随机)
	渲染_画网格(局_画布, 局_布局, 随机, 72)
	渲染_加装饰(局_画布, 随机)
	return &T题_挑战{
		Z帧:   []*image.RGBA{局_画布},
		M目标: 局_布局.目标,
		G格式: "png",
	}, nil
}
